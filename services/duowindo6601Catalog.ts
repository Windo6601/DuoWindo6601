export function getLocalizedLanguageName(englishName: string, targetLang: string = 'ru'): string {
  if (LANGUAGE_TRANSLATIONS[englishName]?.[targetLang]) {
    return LANGUAGE_TRANSLATIONS[englishName][targetLang];
  }
  return englishName;
}

export function getLocalizedCatalogTitle(item: DuoWindo6601CatalogItem, targetLang: string = 'ru'): string {
  const learning = getLocalizedLanguageName(item.learningLanguageName, targetLang);
  const from = getLocalizedLanguageName(item.fromLanguageName, targetLang);
  
  if (targetLang === 'ru') {
    return `${learning} (с ${from.toLowerCase().replace(/ий$/, 'ого').replace(/ой$/, 'ого')})`;
  }
  if (targetLang === 'de') {
    return `${learning} (für ${from}sprachige)`;
  }
  if (targetLang === 'fr') {
    return `${learning} (depuis ${from})`;
  }
  if (targetLang === 'es') {
    return `${learning} (desde ${from})`;
  }
  if (targetLang === 'ja') {
    return `${learning}（${from}話者向け）`;
  }
  if (targetLang === 'zh') {
    return `${learning}（从${from}学）`;
  }
  if (targetLang === 'ar') {
    return `${learning} (للناطقين ب${from})`;
  }
  if (targetLang === 'uk') {
    return `${learning} (з ${from.toLowerCase()})`;
  }
  return `${learning} from ${from}`;
}

