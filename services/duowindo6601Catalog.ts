export function formatLearnerCount(count: number): string {
  if (count >= 1000000) {
    return (count / 1000000).toFixed(1).replace(/\.0$/, "") + "M";
  }
  if (count >= 1000) {
    return (count / 1000).toFixed(0) + "k";
  }
  return count.toString();
}

export function searchCatalog(query: string): DuoWindo6601CatalogItem[] {
  if (!query) return DUOWINDO6601_OFFICIAL_CATALOG;
  const q = query.toLowerCase().trim();
  return DUOWINDO6601_OFFICIAL_CATALOG.filter(item =>
    item.title.toLowerCase().includes(q) ||
    item.learningLanguageName.toLowerCase().includes(q) ||
    item.fromLanguageName.toLowerCase().includes(q) ||
    item.learningLanguage.toLowerCase() === q ||
    item.fromLanguage.toLowerCase() === q
  );
}

