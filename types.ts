export interface RoleplayMessage {
  role: 'user' | 'model';
  text: string;
  audio?: string; // base64
  correction?: string; // For Max users: grammar correction
  isFallback?: boolean; // Indicates if this message was generated by fallback logic due to API limits
}

export interface Exercise {
  id: string;
  originalSentence: string;
  targetTranslation: string; 
  wordBank: string[]; 
  hints?: Record<string, string>;
  type?: 'translation' | 'listening' | 'speech' | 'words' | 'roleplay' | 'illusion' | 'drawing' | 'chess' | 'ishihara' | 'reading';
  isFallback?: boolean; // Indicates if this exercise was generated by fallback logic due to API limits
  // Specific to roleplay
  roleplayData?: {
    topic: string;
    messages: RoleplayMessage[];
    userTurn: boolean;
  };
  // Specific to Reading
  readingData?: {
    title: string;
    text: string;
    mode: 'fill-blanks' | 'write';
    blanks?: { id: string; word: string }[]; // For fill-blanks
    prompt?: string; // For writing
  };
  // Specific to Sound Illusion
  illusionData?: {
    soundText: string;
    optionA: string;
    optionB: string;
    correctOption: 'A' | 'B';
    explanation: string;
  };
  // Specific to Drawing
  drawingData?: {
    character: string;
    instruction: string;
  };
  // Specific to Chess
  chessData?: {
    fen: string; // Forsyth–Edwards Notation
    pgn: string[]; // History
    difficulty: 'beginner' | 'intermediate' | 'grandmaster';
  };
  // Specific to Ishihara
  ishiharaData?: {
    image: string; // base64
    number: string;
  };
}

